def style_sheet(ws, freeze_panes="A2"):
    ws.freeze_panes = freeze_panes
    ws.auto_filter.ref = ws.dimensions
    header_fill = PatternFill("solid", fgColor="1F4E78")
    header_font = Font(color="FFFFFF", bold=True)
    thin_grey = Side(style="thin", color="D9E2F3")
    for cell in ws[1]:
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(wrap_text=True, vertical="center")
        cell.border = Border(bottom=thin_grey)
    ws.row_dimensions[1].height = 32
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = Border(bottom=Side(style="hair", color="E7E6E6"))
    for col_idx in range(1, ws.max_column + 1):
        values = [str(ws.cell(r, col_idx).value or "") for r in range(1, ws.max_row + 1)]
        width = min(max(max((len(v) for v in values), default=10) + 2, 12), 58)
        ws.column_dimensions[get_column_letter(col_idx)].width = width

def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    wb = Workbook()

    ws = wb.active
    ws.title = "Decision Register"
    ws.append(HEADERS)
    for row in REGISTER_ROWS:
        ws.append(row)
    style_sheet(ws)
    ws.freeze_panes = "A2"
    # Format percentage statistics consistently.
    for row in ws.iter_rows(min_row=2, min_col=9, max_col=13):
        for cell in row:
            cell.number_format = '0.00'
    if ws.max_row >= 2:
        tab = Table(displayName="RHPAFeatureDecisions", ref=ws.dimensions)
        tab.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True, showColumnStripes=False)
        ws.add_table(tab)

    summary_ws = wb.create_sheet("Summary")
    summary_ws.append(["Scope", "Keep", "Exclude", "Contextual only", "Total"])
    for row in SUMMARY_ROWS:
        summary_ws.append(row)
    style_sheet(summary_ws)

    notes_ws = wb.create_sheet("Modelling Notes")
    notes_ws.append(["Scope", "Note"])
    for row in MODELLING_NOTES:
        notes_ws.append(row)
    style_sheet(notes_ws)
    notes_ws.column_dimensions["A"].width = 25
    notes_ws.column_dimensions["B"].width = 100

    wb.properties.title = "RHPA Master Feature Decision Register"
    wb.properties.subject = "Approved and provisional NFHS feature-selection decisions"
    wb.properties.creator = "RHPA Project"
    wb.save(OUTPUT)
    print(f"Created: {OUTPUT}")
    print(f"Register entries: {len(REGISTER_ROWS)}")

if __name__ == "__main__":
    main()
